import { useState } from 'react';
import { Download, FileText, Film, Volume2, VolumeX } from 'lucide-react';
import { SparkIcon, UserAvatar } from './ui.jsx';
import Markdown, { CopyButton } from './Markdown.jsx';
import { speak, stopSpeaking, ttsSupported } from '../lib/speech.js';

function Media({ item }) {
  if (item.type === 'video') {
    if (!item.src) {
      return (
        <div className="mt-3 rounded-2xl bg-field text-muted text-sm px-4 py-6 flex items-center gap-3 max-w-xl">
          <Film size={20} className="shrink-0" />
          Generated videos aren't kept after you close the app. Ask Lumina to create it again.
        </div>
      );
    }
    return (
      <video
        src={item.src}
        controls
        playsInline
        style={{ borderRadius: '16px', width: '100%', maxWidth: 640, marginTop: 12, background: '#000' }}
      />
    );
  }
  if (!item.src) {
    return <div className="mt-3 rounded-2xl bg-field text-muted text-sm px-4 py-6 max-w-xl">This image was removed to free up storage.</div>;
  }
  return (
    <div className="mt-3 relative inline-block max-w-full group">
      <img src={item.src} alt="Generated by Lumina AI" style={{ borderRadius: '16px' }} className="max-w-full sm:max-w-md h-auto block" />
      <a
        href={item.src}
        download={`lumina-image-${Date.now()}.png`}
        aria-label="Download image"
        className="absolute right-2 bottom-2 h-9 w-9 rounded-full bg-black/55 text-white flex items-center justify-center hover:bg-black/70"
      >
        <Download size={17} />
      </a>
    </div>
  );
}

export default function Message({ message, userName }) {
  const isUser = message.role === 'user';
  const [speaking, setSpeaking] = useState(false);

  function toggleSpeak() {
    if (speaking) {
      stopSpeaking();
      setSpeaking(false);
    } else {
      setSpeaking(true);
      speak(message.text, { onEnd: () => setSpeaking(false) });
    }
  }

  return (
    <article className="flex gap-3 sm:gap-4 py-4">
      <div className="shrink-0 mt-0.5">{isUser ? <UserAvatar name={userName} size={30} /> : <SparkIcon size={30} />}</div>
      <div className="min-w-0 flex-1">
        <div className="text-xs font-medium text-muted mb-1">{isUser ? 'You' : 'Lumina AI'}</div>

        {isUser && message.attachments?.length > 0 && (
          <div className="flex flex-wrap gap-2 mb-2">
            {message.attachments.map((a, i) =>
              a.preview ? (
                <img key={i} src={a.preview} alt={a.name} style={{ borderRadius: '16px' }} className="h-24 w-auto max-w-[60vw] object-cover" />
              ) : (
                <span key={i} className="inline-flex items-center gap-2 rounded-full bg-field px-3 h-9 text-sm max-w-[70vw]">
                  <FileText size={15} className="shrink-0 text-muted" />
                  <span className="truncate">{a.name}</span>
                </span>
              )
            )}
          </div>
        )}

        {isUser ? (
          message.text && <p className="whitespace-pre-wrap text-[16px] leading-relaxed break-words">{message.text}</p>
        ) : (
          message.text && <Markdown text={message.text} />
        )}

        {message.media?.map((m, i) => <Media key={i} item={m} />)}

        {!isUser && message.text && (
          <div className="mt-2 -ml-2 flex items-center gap-1 text-muted">
            <CopyButton text={message.text} label="Copy" className="inline-flex items-center gap-1.5 rounded-full px-3 h-8 text-xs hover:bg-hover" />
            {ttsSupported() && (
              <button onClick={toggleSpeak} className="inline-flex items-center gap-1.5 rounded-full px-3 h-8 text-xs hover:bg-hover" aria-label={speaking ? 'Stop reading' : 'Read aloud'}>
                {speaking ? <VolumeX size={15} /> : <Volume2 size={15} />}
                <span>{speaking ? 'Stop' : 'Listen'}</span>
              </button>
            )}
          </div>
        )}
      </div>
    </article>
  );
}
